#[cfg(test)]
mod tests {
    use super::*;

    /// sha256 of the v0.8.3 key names, sorted and newline-joined.
    const V083_SHA256: &str = "c7b5e07fd985362004836cb4d1bbb090c69b68f9ee6c2826fe375818e43ba2ad";

    const V083_BOOL_SHA256: &str =
        "5750ff949dd83be04082fb25eb35fa7e8d70f819a7c398f2663056480e1d4a58";
    const V083_INT_SHA256: &str =
        "ff747ba6b5eec8859362c731ccd0d3e51ca358bbaaf362553716674b9ab83350";

    #[test]
    fn types_match_upstream_v083() {
        for (keys, len, sha) in [
            (BOOL_KEYS, 158, V083_BOOL_SHA256),
            (INT_KEYS, 39, V083_INT_SHA256),
        ] {
            assert_eq!(keys.len(), len);
            assert!(keys.windows(2).all(|w| w[0] < w[1]), "sorted and unique");
            assert!(keys.iter().all(|k| CONFIG_KEYS.binary_search(k).is_ok()));
            let joined = keys.join("\n");
            assert_eq!(plugin_toolkit::hash::sha256_hex(joined.as_bytes()), sha);
        }
    }

    #[test]
    fn keys_match_upstream_v083() {
        assert_eq!(CONFIG_KEYS.len(), 365);
        assert!(
            CONFIG_KEYS.windows(2).all(|w| w[0] < w[1]),
            "sorted and unique"
        );
        let joined = CONFIG_KEYS.join("\n");
        assert_eq!(
            plugin_toolkit::hash::sha256_hex(joined.as_bytes()),
            V083_SHA256
        );
    }
}
